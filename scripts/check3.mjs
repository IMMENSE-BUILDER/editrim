import { chromium } from 'playwright';
const b = await chromium.launch({channel:'chrome'});
const p = await b.newPage({viewport:{width:1440,height:1000}});
await p.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
await p.waitForTimeout(900);
await p.locator('.templates-section').scrollIntoViewIfNeeded();
await p.waitForTimeout(500);
await p.screenshot({path:'shots/templates-landing3.png'});
await p.locator('.bento-section').scrollIntoViewIfNeeded();
await p.waitForTimeout(500);
await p.screenshot({path:'shots/bento3.png'});
await p.goto('http://127.0.0.1:5173/editor/new?template=porter-pitch',{waitUntil:'networkidle'});
await p.waitForTimeout(900);
await p.locator('.cv-page').screenshot({path:'shots/porter3.png'});
await p.goto('http://127.0.0.1:5173/dashboard',{waitUntil:'networkidle'});
await p.getByRole('button',{name:/New design/i}).first().click();
await p.waitForTimeout(200);
await p.getByRole('button',{name:/Custom size/i}).click();
await p.waitForTimeout(300);
await p.screenshot({path:'shots/custom-size2.png'});
await b.close();
